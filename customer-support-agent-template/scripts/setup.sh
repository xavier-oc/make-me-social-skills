# =============================================================================
# STATE MANAGEMENT
# =============================================================================

load_config() {
  if [[ -f "$CONFIG_FILE" ]]; then
    cat "$CONFIG_FILE"
  else
    echo "{}"
  fi
}

save_config() {
  local config_json="$1"
  echo "$config_json" | jq '.' > "$CONFIG_FILE"
}

get_config() {
  local key="$1"
  local config
  config=$(load_config)
  echo "$config" | jq -r ".$key // empty"
}

set_config() {
  local key="$1"
  local value="$2"
  local config
  config=$(load_config)
  config=$(echo "$config" | jq --arg key "$key" --arg value "$value" '.$key = $value')
  save_config "$config"
}

is_complete() {
  local config
  config=$(load_config)
  local required=("company_name" "support_email" "support_phone" "email_provider" "email_provider_docs" "calendar_enabled")
  for key in "${required[@]}"; do
    if [[ -z "$(echo "$config" | jq -r ".$key // empty")" ]]; then
      return 1
    fi
  done
  return 0
}

