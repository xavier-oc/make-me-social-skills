generate_google_calendar_helpers() {
  local scripts_dir="$WORKSPACE_DIR/skills/email-support/scripts"
  mkdir -p "$scripts_dir"
  
  cat > "$scripts_dir/calendar_helpers.sh" << 'CAL_EOF'
#!/usr/bin/env bash
# Google Calendar Helper Scripts
# Provides functions for checking availability and creating events.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WORKSPACE_DIR="/home/openclaw2/.openclaw/workspace"
CRED_DIR="$WORKSPACE_DIR/credentials"

# Load .env if it exists
if [[ -f "$WORKSPACE_DIR/.env" ]]; then
  set -a
  source "$WORKSPACE_DIR/.env"
  set +a
fi

source "$CRED_DIR/google_oauth.json" 2>/dev/null || true

get_access_token() {
  local cred_file="$CRED_DIR/google_oauth.json"
  
  if [[ ! -f "$cred_file" ]]; then
    echo "ERROR: Google credentials not found at $cred_file" >&2
    return 1
  fi
  
  local expiry=$(jq -r '.expiry_date' "$cred_file" 2>/dev/null || echo "0")
  local now=$(date +%s)
  
  # Check if token needs refresh
  if (( now < expiry - 60 )); then
    jq -r '.access_token' "$cred_file"
    return 0
  fi
  
  # Refresh the token
  local refresh_token=$(jq -r '.refresh_token' "$cred_file")
  local client_id=$(jq -r '.client_id' "$cred_file")
  local client_secret=$(jq -r '.client_secret' "$cred_file")
  
  local response=$(curl -s --max-time 15 -X POST \
    "https://oauth2.googleapis.com/token" \
    -d "refresh_token=$refresh_token" \
    -d "client_id=$client_id" \
    -d "client_secret=$client_secret" \
    -d "grant_type=refresh_token")
  
  local access_token=$(echo "$response" | jq -r '.access_token // empty')
  
  if [[ -z "$access_token" ]]; then
    echo "ERROR: Failed to refresh token" >&2
    return 1
  fi
  
  # Update credentials file
  local new_expiry=$((now + 3600))
  jq --arg token "$access_token" --argjson expiry "$new_expiry" \
    '.access_token = $token | .expiry_date = $expiry' "$cred_file" > "${cred_file}.tmp" \
    && mv "${cred_file}.tmp" "$cred_file"
  
  echo "$access_token"
}

check_availability() {
  local start_date="$1"  # YYYY-MM-DD
  local start_time="$2"  # HH:MM
  local end_time="${3:-}" # Optional end time
  local calendar_id="${4:-primary}"
  
  local token
  token=$(get_access_token) || return 1
  
  local start_dt="${start_date}T${start_time}:00Z"
  local end_dt=""
  if [[ -n "$end_time" ]]; then
    end_dt="${start_date}T${end_time}:00Z"
  else
    # Default 1 hour meeting
    end_dt=$(date -d "${start_date} ${start_time} +1 hour" -u +"%Y-%m-%dT%H:%M:%SZ" 2>/dev/null || echo "")
  fi
  
  local response=$(curl -s --max-time 20 -X GET \
    "https://www.googleapis.com/calendar/v3/calendars/${calendar_id}/events?timeMin=${start_dt}&timeMax=${end_dt}&singleEvents=true&orderBy=startTime" \
    -H "Authorization: Bearer ${token}" \
    -H "Content-Type: application/json")
  
  echo "$response" | jq '.items'
}

create_event() {
  local summary="$1"
  local start_dt="$2"
  local end_dt="$3"
  local description="${4:-}"
  local attendees="${5:-}"
  local calendar_id="${6:-primary}"
  
  local token
  token=$(get_access_token) || return 1
  
  local payload=$(jq -n \
    --arg summary "$summary" \
    --arg start "$start_dt" \
    --arg end "$end_dt" \
    --arg description "$description" \
    '{
      summary: $summary,
      start: {dateTime: $start, timeZone: "UTC"},
      end: {dateTime: $end, timeZone: "UTC"},
      description: $description,
      reminders: {
        useDefault: false,
        overrides: [
          {method: "email", minutes: 60},
          {method: "popup", minutes: 15}
        ]
      }
    }')
  
  local response=$(curl -s --max-time 20 -X POST \
    "https://www.googleapis.com/calendar/v3/calendars/${calendar_id}/events" \
    -H "Authorization: Bearer ${token}" \
    -H "Content-Type: application/json" \
    -d "$payload")
  
  local event_id=$(echo "$response" | jq -r '.id // empty')
  if [[ -n "$event_id" && "$event_id" != "null" ]]; then
    echo "Event created: $event_id"
    echo "$response" | jq '{id, summary, start, end, hangoutLink}'
  else
    echo "ERROR: Failed to create event" >&2
    echo "$response" | jq . >&2
    return 1
  fi
}
CAL_EOF

  chmod +x "$scripts_dir/calendar_helpers.sh"
  
  # Also copy to sms-support if calendar enabled
  local sms_scripts_dir="$WORKSPACE_DIR/skills/sms-support/scripts"
  cp "$scripts_dir/calendar_helpers.sh" "$sms_scripts_dir/"
  
  echo "Created calendar helper scripts"
}

