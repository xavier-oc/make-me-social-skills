echo "---"

if [[ "\$FULL_CONTENT" == true ]]; then
  # Fetch full content for each message
  mapfile -t MSGS < <(echo "\$RESPONSE" | jq -c '.data[]' 2>/dev/null || echo "")
  RESULTS_FILE=\$(mktemp)

