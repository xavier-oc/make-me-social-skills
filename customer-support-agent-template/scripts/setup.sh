      --arg id "\$MSG_ID" \\
      --arg subject "\$SUBJECT" \\
      --arg from "\$FROM" \\
      --arg date "\$DATE" \\
      --arg folderId "\$MSG_FOLDER_ID" \\
      --arg content "\$CONTENT" \\
      '{messageId: \$id, subject: \$subject, from: \$from, receivedTime: \$date, folderId: \$folderId, content: \$content}' \\
      >> "\$RESULTS_FILE"
  done

  if [[ -s "\$RESULTS_FILE" ]]; then
    jq -s '.' "\$RESULTS_FILE"
  else
    echo "[]"
  fi
  rm -f "\$RESULTS_FILE"
else
  echo "\$RESPONSE" | jq '[.data[] | {
    messageId,
    subject,
    from: .fromAddress,
    sender,
    receivedTime,
    summary,
    folderId,
