#!/usr/bin/env bash
# Customer Support Agent Template - Setup Wizard Script
# This script is run by the agent when the user says "start support setup"

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SKILL_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
